#!/usr/bin/env node
/**
 * 将 github-markdown-css 的 dark/light 两份样式表合并为一份，
 * 通过 :root 上的 data-theme 属性切换。
 *
 * 暗色（默认）：:root:not([data-theme="light"]) .markdown-body
 * 亮色：       :root[data-theme="light"] .markdown-body
 *
 * 输出到 frontend/src/assets/github-markdown-combined.css
 */

const fs = require('fs')
const path = require('path')

const base = path.resolve(__dirname, '..', 'frontend', 'node_modules', 'github-markdown-css')
const outDir = path.resolve(__dirname, '..', 'frontend', 'src', 'assets')

const darkCss = fs.readFileSync(path.join(base, 'github-markdown-dark.css'), 'utf-8')
const lightCss = fs.readFileSync(path.join(base, 'github-markdown-light.css'), 'utf-8')

/**
 * 将 CSS 中每个 `.markdown-body` 选择器替换为指定的包装选择器。
 * 处理多选择器规则（逗号分隔）和块级结构。
 */
function wrapSelectors(css, wrapper) {
  // 将 .markdown-body 替换为 wrapper .markdown-body
  // 同时处理 .markdown-body 出现在选择器列表中的情况
  return css.replace(/\.markdown-body/g, `${wrapper} .markdown-body`)
}

const darkWrapped = wrapSelectors(darkCss, ':root:not([data-theme="light"])')
const lightWrapped = wrapSelectors(lightCss, ':root[data-theme="light"]')

const output = `/* Auto-generated by scripts/build-markdown-css.js — DO NOT EDIT */
/* GitHub Markdown Dark Theme (default) */
${darkWrapped}

/* GitHub Markdown Light Theme */
${lightWrapped}
`

fs.writeFileSync(path.join(outDir, 'github-markdown-combined.css'), output, 'utf-8')
console.log('✓ Generated github-markdown-combined.css')
